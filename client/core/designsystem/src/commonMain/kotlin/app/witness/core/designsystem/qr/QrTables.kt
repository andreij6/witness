    )

    fun size(version: Int): Int = version * 4 + 17

    fun eccPerBlock(version: Int, ecc: QrEcc): Int = eccCodewordsPerBlock[ecc.ordinal][version]

    fun blocks(version: Int, ecc: QrEcc): Int = errorCorrectionBlocks[ecc.ordinal][version]

    fun rawDataModules(version: Int): Int {
        var result = (16 * version + 128) * version + 64
        if (version >= 2) {
            val align = version / 7 + 2
            result -= (25 * align - 10) * align - 55
            if (version >= 7) result -= 36
        }
        return result
    }

    fun dataCodewords(version: Int, ecc: QrEcc): Int =
        rawDataModules(version) / 8 - eccPerBlock(version, ecc) * blocks(version, ecc)

    fun alignmentPositions(version: Int): IntArray {
        if (version == 1) return IntArray(0)
        val count = version / 7 + 2
        val step = (version * 8 + count * 3 + 5) / (count * 4 - 4) * 2
        val result = IntArray(count)
        result[0] = 6
        var pos = size(version) - 7
        for (i in count - 1 downTo 1) {
            result[i] = pos
            pos -= step
        }
        return result
    }

    fun formatBits(ecc: QrEcc, mask: Int): Int {
        val data = ecc.formatBits shl 3 or mask
        var rem = data
        repeat(10) { rem = (rem shl 1) xor ((rem ushr 9) * 0x537) }
        return (data shl 10 or rem) xor 0x5412
    }

    fun versionBits(version: Int): Int {
        var rem = version
        repeat(12) { rem = (rem shl 1) xor ((rem ushr 11) * 0x1F25) }
        return version shl 12 or rem
    }
}
